#!/usr/bin/env node
// Checks the link between the feature data (doc/features/{md,mm}.json) and the journeys (their `proves:` fields).
// Plain Node, no dependencies. Plan: doc/release/PLAN-0.6.md, slice 3. Data: doc/features/README.md.
// Fails (exit 1): a `proves` id that is not in the data, or is of the other machine; a journey with no `proves` field;
// in the guide (doc/guide/, scripts/mdmm-guide-md.mjs checkGuide): a rows tag, gap, key or table that names nothing,
// an en or em dash, an exclamation mark or a banned word (doc/guide/STYLE.md).
// Reports (exit 0; --strict makes them fail): done rows with no journey; done rows in no guide chapter; guide sections
// to review (their rows changed since stamped); guide pictures (shot:name) that no journey snapshots.
// Writes doc/features/unproved-<machine>.md: the done rows with no journey, by chapter (the work list of slice 5).
// Usage: node scripts/mdmm-features-check.mjs [--strict] [--no-write]

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readJourneys, journeysByRow, snapshotNames } from './mdmm-journey-index.mjs';
import { checkGuide, chapterFiles, parseChapter, partsOf } from './mdmm-guide-md.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MACHINES = ['md', 'mm'];
const strict = process.argv.includes('--strict');
const write = !process.argv.includes('--no-write');

const data = Object.fromEntries(MACHINES.map((m) => [m, JSON.parse(fs.readFileSync(path.join(root, 'doc', 'features', `${m}.json`), 'utf8'))]));
const rowById = new Map(MACHINES.flatMap((m) => data[m].rows.map((r) => [r.id, r])));
const journeys = readJourneys(root);
const by = journeysByRow(journeys);

const errors = [];
for (const j of journeys) {
	const where = `${j.file}:${j.line} ${j.name}`;
	if (j.proves === undefined) { errors.push(`${where}: no proves field (use proves: [] for a journey of the page itself)`); continue; }
	if (j.proves === null) { errors.push(`${where}: proves must be a literal list of row ids`); continue; }
	for (const id of j.proves) {
		if (!rowById.has(id)) errors.push(`${where}: proves ${id}, which is not in the data`);
		else if (!id.toLowerCase().startsWith(j.machine + '-')) errors.push(`${where}: proves ${id}, a row of the other machine`);
	}
}

const reports = [];
const snaps = snapshotNames(root);
const out = [];
for (const m of MACHINES) {
	const rows = data[m].rows;
	const chapters = data[m].doc.filter((b) => b.type === 'table').map((b) => b.chapter);
	const js = journeys.filter((j) => j.machine === m);
	out.push(`${m.toUpperCase()}: ${js.length} journeys, ${js.filter((j) => j.proves?.length).length} prove rows`);
	let done = 0, proved = 0;
	const unproved = [];
	for (const ch of chapters) {
		const d = rows.filter((r) => r.chapter === ch && r.status === 'done');
		const p = d.filter((r) => by.has(r.id));
		done += d.length; proved += p.length;
		unproved.push([ch, d.filter((r) => !by.has(r.id))]);
		out.push(`  ${String(d.length).padStart(3)} done ${String(p.length).padStart(3)} proved ${String(d.length - p.length).padStart(3)} unproved  ${ch}`);
	}
	out.push(`  ${String(done).padStart(3)} done ${String(proved).padStart(3)} proved ${String(done - proved).padStart(3)} unproved  total`);
	const missing = unproved.reduce((n, [, l]) => n + l.length, 0);
	if (missing) reports.push(`${m}: ${missing} done rows have no journey`);
	for (const f of chapterFiles(root, m)) for (const part of partsOf(parseChapter(f.src))) for (const b of part.blocks)
		if (b.type === 'img' && b.src.startsWith('shot:') && !snaps.has(b.src.slice(5))) reports.push(`${path.relative(root, f.file)}:${b.line}: picture "${b.src.slice(5)}": no journey snapshots it yet`);
	if (write) fs.writeFileSync(path.join(root, 'doc', 'features', `unproved-${m}.md`), unprovedList(m, unproved, done, proved));
}

function unprovedList(m, unproved, done, proved) {
	const n = done - proved;
	const lines = [
		`# ${m.toUpperCase()}: done rows with no journey`,
		'',
		`> Generated by scripts/mdmm-features-check.mjs from doc/features/${m}.json and the journeys' \`proves:\` fields; do not edit. The work list of slice 5 (doc/release/PLAN-0.6.md): one journey with a snapshot for each row.`,
		'',
		`${n} of ${done} done rows have no journey.`,
	];
	for (const [ch, rows] of unproved) {
		if (!rows.length) continue;
		lines.push('', `## ${ch} (${rows.length})`, '');
		for (const r of rows) lines.push(`- ${r.id} p.${r.manual}: ${r.function}`);
	}
	return lines.join('\n') + '\n';
}

// the guide against the data: broken references and style fail; sections to review and untagged rows are reported
const guide = checkGuide(root, data, by);
errors.push(...guide.errors);
reports.push(...guide.stale.map((x) => `guide: ${x}`));
const untagged = MACHINES.map((m) => {
	const tagged = new Set(chapterFiles(root, m).flatMap((f) => partsOf(parseChapter(f.src)).flatMap((p) => p.rows)));
	return [m, data[m].rows.filter((r) => r.status === 'done' && !tagged.has(r.id))];
});

console.log(out.join('\n'));
for (const [m, list] of untagged) if (list.length) console.log(`\n${m.toUpperCase()}: done rows in no guide chapter (${list.length}): ${list.slice(0, 12).map((r) => r.id).join(' ')}${list.length > 12 ? ' ...' : ''}`);
if (reports.length) {
	const shown = reports.slice(0, 20);
	console.log('\nreported' + (strict ? ' (--strict: these fail)' : '') + ':\n' + shown.join('\n') + (reports.length > shown.length ? `\n... and ${reports.length - shown.length} more` : ''));
}
if (errors.length) console.error('\nerrors:\n' + errors.join('\n'));
process.exit(errors.length || (strict && reports.length) ? 1 : 0);
